class Command(BaseCommand):
    help = 'Наполняет ЭТАП 6 — Услуги полными чек-листами (лишние уроки удаляет).'

    @transaction.atomic
    def handle(self, *args, **options):
        course = Course.objects.filter(title=COURSE_TITLE).first()
        if not course:
            self.stdout.write(self.style.WARNING(f'Курс «{COURSE_TITLE}» не найден.'))
            return
        topic = Topic.objects.filter(course=course, title=TOPIC_TITLE).first()
        if not topic:
            self.stdout.write(self.style.WARNING(f'Этап «{TOPIC_TITLE}» не найден.'))
            return

        removed = Lesson.objects.filter(topic=topic, title__in=REMOVE).delete()
        self.stdout.write(f'Удалено лишних уроков: {removed[0]}')

        blocks_n = 0
        for order, (title, items) in enumerate(SERVICES, start=1):
            lesson, _ = Lesson.objects.get_or_create(
                topic=topic, title=title,
                defaults={'order': order, 'kind': Lesson.Kind.CONTENT, 'is_published': True})
            lesson.order = order
            lesson.save(update_fields=['order'])
            # НЕ теряем загруженные вручную фото: сохраняем их и вернём в конец урока.
            saved_imgs = [
                (b.caption, b.image.name)
                for b in lesson.blocks.filter(kind=LessonBlock.Kind.IMAGE)
                if b.image and b.image.name
            ]
            lesson.blocks.all().delete()
            b_order = 0
            for b_order, (kind, payload) in enumerate(items, start=1):
                if kind == 'text':
                    LessonBlock.objects.create(lesson=lesson, kind=LessonBlock.Kind.TEXT,
                                               order=b_order, text=payload)
                elif kind == 'image':
                    LessonBlock.objects.create(lesson=lesson, kind=LessonBlock.Kind.IMAGE,
                                               order=b_order, caption=payload)
                elif kind == 'video':
                    url, caption = payload
                    LessonBlock.objects.create(lesson=lesson, kind=LessonBlock.Kind.VIDEO,
                                               order=b_order, video_url=url, caption=caption)
                blocks_n += 1
            # Возвращаем ранее загруженные фото (чтобы повторный сид их не стирал).
            for cap, name in saved_imgs:
                b_order += 1
                blk = LessonBlock(lesson=lesson, kind=LessonBlock.Kind.IMAGE,
                                  order=b_order, caption=cap or 'Фото')
                blk.image.name = name
                blk.save()
                blocks_n += 1
            self.stdout.write(f'  ✓ {title} ({len(items)} блоков, сохранено фото: {len(saved_imgs)})')

        quiz = Lesson.objects.filter(topic=topic, title='Тест', kind=Lesson.Kind.QUIZ).first()
        q_n = 0
        if quiz:
            quiz.order = len(SERVICES) + 1
            quiz.save(update_fields=['order'])
            quiz.questions.all().delete()
            for q_order, (q_text, answers) in enumerate(QUIZ, start=1):
                question = Question.objects.create(lesson=quiz, text=q_text, order=q_order)
                for a_order, (a_text, is_correct) in enumerate(answers, start=1):
                    Answer.objects.create(question=question, text=a_text,
                                          is_correct=is_correct, order=a_order)
                q_n += 1
            self.stdout.write(f'  ✓ Тест: {q_n} вопросов')

        self.stdout.write(self.style.SUCCESS(
            f'Готово. Блоков: {blocks_n}, вопросов в тесте: {q_n}.'
        ))
