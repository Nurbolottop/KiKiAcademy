class Command(BaseCommand):
    help = 'Создаёт структуру обучения менеджера (12 этапов) и привязывает к роли MANAGER.'

    @transaction.atomic
    def handle(self, *args, **options):
        course, created = Course.objects.get_or_create(
            title=COURSE_TITLE,
            defaults={'icon': COURSE_ICON, 'order': 3,
                      'description': 'Программа обучения менеджера: управление объектами и '
                                     'персоналом, контроль качества, клиенты, CRM, инвентарь, '
                                     'доп.продажи и отчётность.'},
        )
        self.stdout.write(('Создан' if created else 'Найден') + f' курс: {course.title}')

        manager = Role.objects.filter(code=Role.Code.MANAGER).first()
        if manager:
            RoleCourse.objects.get_or_create(role=manager, course=course,
                                             defaults={'is_required': True})
            self.stdout.write(f'Курс назначен роли: {manager.title}')
        else:
            self.stdout.write(self.style.WARNING('Роль MANAGER не найдена — курс не назначен.'))

        topics_n = lessons_n = 0
        for t_order, (stage_title, lessons) in enumerate(CURRICULUM, start=1):
            topic, t_created = Topic.objects.get_or_create(
                course=course, title=stage_title, defaults={'order': t_order},
            )
            if not t_created and topic.order != t_order:
                topic.order = t_order
                topic.save(update_fields=['order'])
            topics_n += int(t_created)

            for l_order, (lesson_title, kind) in enumerate(lessons, start=1):
                lesson, l_created = Lesson.objects.get_or_create(
                    topic=topic, title=lesson_title,
                    defaults={'order': l_order, 'kind': kind, 'is_published': True},
                )
                if not l_created and lesson.order != l_order:
                    lesson.order = l_order
                    lesson.save(update_fields=['order'])
                lessons_n += int(l_created)

        self.stdout.write(self.style.SUCCESS(
            f'Готово. Новых тем: {topics_n}, уроков: {lessons_n}.'
        ))
