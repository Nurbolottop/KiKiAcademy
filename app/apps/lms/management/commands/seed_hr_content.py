def _c(html, color):
    return (f'<div style="background:{color}1f;border-left:4px solid {color};'
            f'padding:12px 16px;border-radius:10px;margin:14px 0;">{html}</div>')


def warn(h): return _c('⚠️ ' + h, '#ef4444')
def note(h): return _c('ℹ️ ' + h, '#6c63ff')
def ok(h): return _c('✅ ' + h, '#22c55e')
def li(*x): return '<ul>' + ''.join(f'<li>{i}</li>' for i in x) + '</ul>'
def ol(*x): return '<ol>' + ''.join(f'<li>{i}</li>' for i in x) + '</ol>'
def t(h): return ('text', h)


