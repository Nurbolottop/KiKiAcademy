MAP = {
    'course_title': (Course, 'title_ky'),
    'course_desc': (Course, 'description_ky'),
    'topic_title': (Topic, 'title_ky'),
    'lesson_title': (Lesson, 'title_ky'),
    'lesson_desc': (Lesson, 'description_ky'),
    'block_text': (LessonBlock, 'text_ky'),
    'block_caption': (LessonBlock, 'caption_ky'),
    'question_text': (Question, 'text_ky'),
    'answer_text': (Answer, 'text_ky'),
}


class Command(BaseCommand):
    help = 'Кыргызский перевод курса менеджера, часть 2 (только *_ky).'

    @transaction.atomic
    def command_body(self):
        updated = 0
        missing = 0
        for key, (Model, field) in MAP.items():
            for oid, ky in KY.get(key, {}).items():
                obj = Model.objects.filter(id=oid).first()
                if obj is None:
                    missing += 1
                    continue
                setattr(obj, field, ky)
                obj.save(update_fields=[field])
                updated += 1
        self.stdout.write(self.style.SUCCESS(f'Обновлено *_ky: {updated}. Не найдено: {missing}.'))

    def handle(self, *args, **options):
        self.command_body()
