class Command(BaseCommand):
    help = 'Заполняет реальные описания уроков курса «Обучение клинера» (перезаписывает).'

    def handle(self, *args, **options):
        course = Course.objects.filter(title=COURSE_TITLE).first()
        if not course:
            self.stdout.write(self.style.WARNING(f'Курс «{COURSE_TITLE}» не найден.'))
            return

        updated = missing = 0
        for lesson in Lesson.objects.filter(topic__course=course):
            text = DESCRIPTIONS.get(lesson.title)
            if not text:
                missing += 1
                continue
            if lesson.description != text:
                lesson.description = text
                lesson.save(update_fields=['description'])
                updated += 1

        self.stdout.write(self.style.SUCCESS(
            f'Готово. Обновлено описаний: {updated}, без описания в словаре: {missing}.'
        ))
