class Command(BaseCommand):
    help = 'Объединяет мелкие уроки оператора в крупные (перенос блоков, без потери контента).'

    @transaction.atomic
    def command_body(self):
        try:
            course = Course.objects.get(title=COURSE_TITLE)
        except Course.DoesNotExist:
            self.stderr.write(self.style.ERROR(f'Курс «{COURSE_TITLE}» не найден.'))
            return

        topics = {t.order: t for t in course.topics.all()}
        moved_blocks = merged_away = 0
        skipped = []

        for topic_order, plan in MERGES.items():
            topic = topics.get(topic_order)
            if topic is None:
                skipped.append(f'нет этапа order={topic_order}')
                continue

            for pos, (final_title, sources) in enumerate(plan, start=1):
                lessons = []
                for s in sources:
                    l = topic.lessons.filter(title=s).first()
                    if l:
                        lessons.append(l)
                    else:
                        skipped.append(f'этап {topic_order}: не найден урок «{s}»')
                if not lessons:
                    continue

                target = lessons[0]
                max_order = max([b.order for b in target.blocks.all()], default=0)
                for src in lessons[1:]:
                    for b in src.blocks.all().order_by('order', 'id'):
                        max_order += 1
                        b.lesson = target
                        b.order = max_order
                        b.save(update_fields=['lesson', 'order'])
                        moved_blocks += 1
                    src.delete()
                    merged_away += 1

                target.title = final_title
                target.order = pos
                target.save(update_fields=['title', 'order'])

        self.stdout.write(self.style.SUCCESS(
            f'Готово. Перенесено блоков: {moved_blocks}. '
            f'Объединено (удалено пустых) уроков: {merged_away}.'))
        for t in course.topics.all().order_by('order', 'id'):
            self.stdout.write(f'  {t.title}: уроков {t.lessons.count()}')
        if skipped:
            self.stdout.write(self.style.WARNING('Пропущено:'))
            for s in skipped:
                self.stdout.write('  - ' + s)

    def handle(self, *args, **options):
        self.command_body()
