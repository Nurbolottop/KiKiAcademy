class Command(BaseCommand):
    help = 'Дополняет курс оператора подробным текстом (только добавление).'

    @transaction.atomic
    def command_body(self):
        course = Course.objects.get(id=COURSE_ID)
        topics = {t.title: t for t in course.topics.all()}
        added = 0
        skipped = []
        for (topic_title, lesson_title), blocks in ENRICH.items():
            topic = topics.get(topic_title)
            if topic is None:
                skipped.append('нет этапа: ' + topic_title)
                continue
            lesson = topic.lessons.filter(title=lesson_title).first()
            if lesson is None:
                skipped.append('нет урока: ' + topic_title + ' / ' + lesson_title)
                continue
            existing_txt = set(b.text for b in lesson.blocks.all())
            existing_cap = set(b.caption for b in lesson.blocks.all())
            mo = max([b.order for b in lesson.blocks.all()], default=0)
            for kind, val in blocks:
                if kind == 'text':
                    if val in existing_txt:
                        continue
                    mo += 1
                    LessonBlock.objects.create(lesson=lesson, kind='TEXT', order=mo, text=val)
                    existing_txt.add(val)
                    added += 1
                elif kind == 'image':
                    if val in existing_cap:
                        continue
                    mo += 1
                    LessonBlock.objects.create(lesson=lesson, kind='IMAGE', order=mo, caption=val)
                    existing_cap.add(val)
                    added += 1
                elif kind == 'video':
                    if val in existing_cap:
                        continue
                    mo += 1
                    LessonBlock.objects.create(lesson=lesson, kind='VIDEO', order=mo,
                                               caption=val, video_url='')
                    existing_cap.add(val)
                    added += 1
        self.stdout.write(self.style.SUCCESS(f'Добавлено блоков: {added}'))
        for s in skipped:
            self.stdout.write('  ПРОПУСК: ' + s)

    def handle(self, *args, **options):
        self.command_body()
