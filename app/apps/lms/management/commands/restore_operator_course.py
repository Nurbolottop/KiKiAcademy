class Command(BaseCommand):
    help = 'РАЗОВО пересобирает курс «Обучение оператора» по тексту заказчика.'

    @transaction.atomic
    def handle(self, *args, **options):
        course = Course.objects.filter(title=COURSE_TITLE).first()
        if not course:
            self.stdout.write(self.style.WARNING(f'Курс «{COURSE_TITLE}» не найден.'))
            return

        # Полностью пересобираем структуру курса под присланные этапы.
        course.topics.all().delete()

        lessons_n = blocks_n = 0
        for t_order, (topic_title, lessons) in enumerate(COURSE, start=1):
            topic = Topic.objects.create(course=course, title=topic_title, order=t_order)
            for l_order, (lesson_title, html) in enumerate(lessons, start=1):
                lesson = Lesson.objects.create(
                    topic=topic, title=lesson_title, order=l_order,
                    kind=Lesson.Kind.CONTENT, is_published=True)
                LessonBlock.objects.create(
                    lesson=lesson, kind=LessonBlock.Kind.TEXT, order=1, text=html)
                lessons_n += 1
                blocks_n += 1
            self.stdout.write(f'  ✓ {topic_title} ({len(lessons)} уроков)')

        self.stdout.write(self.style.SUCCESS(
            f'Готово. Этапов: {len(COURSE)}, уроков: {lessons_n}, блоков: {blocks_n}.'
        ))
