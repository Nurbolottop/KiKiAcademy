class Command(BaseCommand):
    help = 'Наполняет курс «Обучение СММ / Мобилографа» — этапы 1-7,10 + аттестация (11).'

    @transaction.atomic
    def handle(self, *args, **options):
        course = Course.objects.filter(title=COURSE_TITLE).first()
        if not course:
            self.stdout.write(self.style.WARNING(f'Курс «{COURSE_TITLE}» не найден.'))
            return

        blocks_n = q_n = 0
        for topic_title, data in STAGES.items():
            topic = Topic.objects.filter(course=course, title=topic_title).first()
            if not topic:
                self.stdout.write(self.style.WARNING(f'  Этап не найден: {topic_title}'))
                continue
            for l_order, (lesson_title, blocks) in enumerate(data['lessons'], start=1):
                lesson = Lesson.objects.filter(topic=topic, title=lesson_title).first()
                if not lesson:
                    continue
                lesson.order = l_order
                lesson.save(update_fields=['order'])
                lesson.blocks.all().delete()
                for b_order, item in enumerate(blocks, start=1):
                    if item[0] == 'image':
                        LessonBlock.objects.create(lesson=lesson, kind=LessonBlock.Kind.IMAGE,
                                                   order=b_order, caption=item[1])
                    else:
                        LessonBlock.objects.create(lesson=lesson, kind=LessonBlock.Kind.TEXT,
                                                   order=b_order, text=item[1])
                    blocks_n += 1
            quiz = Lesson.objects.filter(topic=topic, title='Тест', kind=Lesson.Kind.QUIZ).first()
            if quiz and data.get('quiz'):
                quiz.order = len(data['lessons']) + 1
                quiz.pass_threshold = PASS_THRESHOLD
                quiz.save(update_fields=['order', 'pass_threshold'])
                quiz.questions.all().delete()
                for q_order, (q_text, answers) in enumerate(data['quiz'], start=1):
                    question = Question.objects.create(lesson=quiz, text=q_text, order=q_order)
                    for a_order, (a_text, is_correct) in enumerate(answers, start=1):
                        Answer.objects.create(question=question, text=a_text,
                                              is_correct=is_correct, order=a_order)
                    q_n += 1
            self.stdout.write(f'  ✓ {topic_title}')

        att = Topic.objects.filter(course=course, title__startswith='ЭТАП 11').first()
        if att:
            exam, _ = Lesson.objects.get_or_create(topic=att, title='Общий экзамен',
                defaults={'kind': Lesson.Kind.QUIZ, 'order': 1})
            exam.kind = Lesson.Kind.QUIZ
            exam.order = 1
            exam.pass_threshold = PASS_THRESHOLD
            exam.save()
            exam.questions.all().delete()
            for q_order, (q_text, answers) in enumerate(EXAM, start=1):
                question = Question.objects.create(lesson=exam, text=q_text, order=q_order)
                for a_order, (a_text, is_correct) in enumerate(answers, start=1):
                    Answer.objects.create(question=question, text=a_text,
                                          is_correct=is_correct, order=a_order)
            q_n += len(EXAM)
            order = 2
            for title, blocks in ATTESTATION.items():
                lesson, _ = Lesson.objects.get_or_create(topic=att, title=title,
                    defaults={'kind': Lesson.Kind.CONTENT, 'order': order})
                lesson.kind = Lesson.Kind.CONTENT
                lesson.order = order
                lesson.save(update_fields=['kind', 'order'])
                lesson.blocks.all().delete()
                for b_order, (kind, payload) in enumerate(blocks, start=1):
                    LessonBlock.objects.create(lesson=lesson, kind=LessonBlock.Kind.TEXT,
                                               order=b_order, text=payload)
                    blocks_n += 1
                order += 1
            self.stdout.write(f'  ✓ ЭТАП 11 — аттестация (экзамен {len(EXAM)} вопросов)')

        self.stdout.write(self.style.SUCCESS(f'Готово. Блоков: {blocks_n}, вопросов: {q_n}.'))
