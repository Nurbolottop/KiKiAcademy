class Command(BaseCommand):
    help = 'Наполняет ЭТАП 12 — Финальная аттестация менеджера (экзамен + практика + статус).'

    @transaction.atomic
    def handle(self, *args, **options):
        course = Course.objects.filter(title=COURSE_TITLE).first()
        if not course:
            self.stdout.write(self.style.WARNING(f'Курс «{COURSE_TITLE}» не найден.'))
            return
        topic = Topic.objects.filter(course=course, title=TOPIC_TITLE).first()
        if not topic:
            self.stdout.write(self.style.WARNING(f'Этап «{TOPIC_TITLE}» не найден.'))
            return

        exam, _ = Lesson.objects.get_or_create(
            topic=topic, title='Общий экзамен',
            defaults={'kind': Lesson.Kind.QUIZ, 'order': 1})
        exam.kind = Lesson.Kind.QUIZ
        exam.order = 1
        exam.pass_threshold = PASS_THRESHOLD
        exam.description = (
            'Итоговый экзамен по программе обучения менеджера. '
            f'Для прохождения нужно набрать не меньше {PASS_THRESHOLD}%.')
        exam.save()
        exam.questions.all().delete()
        for q_order, (q_text, answers) in enumerate(EXAM, start=1):
            question = Question.objects.create(lesson=exam, text=q_text, order=q_order)
            for a_order, (a_text, is_correct) in enumerate(answers, start=1):
                Answer.objects.create(question=question, text=a_text,
                                      is_correct=is_correct, order=a_order)
        self.stdout.write(f'  ✓ Общий экзамен: {len(EXAM)} вопросов (проход {PASS_THRESHOLD}%)')

        order = 2
        for title, blocks in CONTENT.items():
            lesson, _ = Lesson.objects.get_or_create(
                topic=topic, title=title,
                defaults={'kind': Lesson.Kind.CONTENT, 'order': order})
            lesson.kind = Lesson.Kind.CONTENT
            lesson.order = order
            lesson.save(update_fields=['kind', 'order'])
            lesson.blocks.all().delete()
            for b_order, (kind, payload) in enumerate(blocks, start=1):
                LessonBlock.objects.create(lesson=lesson, kind=LessonBlock.Kind.TEXT,
                                           order=b_order, text=payload)
            self.stdout.write(f'  ✓ {title} ({len(blocks)} блоков)')
            order += 1

        self.stdout.write(self.style.SUCCESS(
            f'Готово. Экзамен: {len(EXAM)} вопросов, контентных уроков: {len(CONTENT)}.'
        ))
