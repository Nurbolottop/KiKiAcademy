class Command(BaseCommand):
    help = 'Наполняет подробным текстом урок «Съёмка» (СММ, ЭТАП 3).'

    def handle(self, *args, **options):
        lesson = (Lesson.objects
                  .filter(topic__course__title=COURSE_TITLE,
                          topic__title=TOPIC_TITLE, title=LESSON_TITLE)
                  .first())
        if lesson is None:
            self.stderr.write(self.style.ERROR('Урок «Съёмка» не найден.'))
            return

        updated = 0
        for b in lesson.blocks.all().order_by('order', 'id'):
            if b.kind != 'TEXT':
                continue
            for marker, new_html in BLOCKS.items():
                if marker in b.text:
                    b.text = new_html
                    b.save(update_fields=['text'])
                    updated += 1
                    break

        self.stdout.write(self.style.SUCCESS(
            f'Готово. Обновлено текстовых блоков: {updated} из {len(BLOCKS)}.'))
