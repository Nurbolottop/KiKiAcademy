STAGES = {
    'ЭТАП 1 — Введение': STAGE1,
    'ЭТАП 2 — Работа с клиентом': STAGE2,
    'ЭТАП 4 — Услуги компании': STAGE4,
}


class Command(BaseCommand):
    help = 'Наполняет курс «Обучение оператора» — этапы 1, 2, 4 (контент + тесты).'

    @transaction.atomic
    def handle(self, *args, **options):
        course = Course.objects.filter(title=COURSE_TITLE).first()
        if not course:
            self.stdout.write(self.style.WARNING(
                f'Курс «{COURSE_TITLE}» не найден. Сначала: seed_operator_curriculum.'))
            return

        # Источник подробного контента услуг (курс клинера, ЭТАП 6).
        cleaner_topic = Topic.objects.filter(
            course__title=CLEANER_COURSE_TITLE, title=CLEANER_TOPIC_TITLE).first()

        blocks_n = q_n = copied_n = 0
        for topic_title, data in STAGES.items():
            topic = Topic.objects.filter(course=course, title=topic_title).first()
            if not topic:
                self.stdout.write(self.style.WARNING(f'  Этап не найден: {topic_title}'))
                continue

            for l_order, (lesson_title, blocks) in enumerate(data['lessons'], start=1):
                lesson = Lesson.objects.filter(topic=topic, title=lesson_title).first()
                if not lesson:
                    self.stdout.write(self.style.WARNING(f'    Урок не найден: {lesson_title}'))
                    continue
                lesson.order = l_order
                lesson.save(update_fields=['order'])
                lesson.blocks.all().delete()
                b_order = 0
                for b_order, (kind, payload) in enumerate(blocks, start=1):
                    LessonBlock.objects.create(lesson=lesson, kind=LessonBlock.Kind.TEXT,
                                               order=b_order, text=payload)
                    blocks_n += 1

                # Подтягиваем подробный контент услуги из курса клинера.
                src_title = CLEANER_SOURCES.get(lesson_title)
                if src_title and cleaner_topic:
                    src_lesson = Lesson.objects.filter(
                        topic=cleaner_topic, title=src_title).first()
                    if src_lesson:
                        b_order += 1
                        LessonBlock.objects.create(
                            lesson=lesson, kind=LessonBlock.Kind.TEXT, order=b_order,
                            text=note('<strong>Подробно об услуге</strong> (из обучения клинера) — '
                                      'чтобы детально консультировать клиента.'))
                        blocks_n += 1
                        for src in src_lesson.blocks.order_by('order', 'id'):
                            b_order += 1
                            new = LessonBlock(lesson=lesson, kind=src.kind, order=b_order,
                                              text=src.text, caption=src.caption,
                                              video_url=src.video_url)
                            if src.image:
                                new.image.name = src.image.name  # тот же файл в media
                            new.save()
                            blocks_n += 1
                            copied_n += 1

            # Тест этапа
            quiz = Lesson.objects.filter(topic=topic, title='Тест', kind=Lesson.Kind.QUIZ).first()
            if quiz and data.get('quiz'):
                quiz.order = len(data['lessons']) + 1
                quiz.pass_threshold = PASS_THRESHOLD
                quiz.save(update_fields=['order', 'pass_threshold'])
                quiz.questions.all().delete()
                for q_order, (q_text, answers) in enumerate(data['quiz'], start=1):
                    question = Question.objects.create(lesson=quiz, text=q_text, order=q_order)
                    for a_order, (a_text, is_correct) in enumerate(answers, start=1):
                        Answer.objects.create(question=question, text=a_text,
                                              is_correct=is_correct, order=a_order)
                    q_n += 1
            self.stdout.write(f'  ✓ {topic_title}')

        self.stdout.write(self.style.SUCCESS(
            f'Готово. Блоков: {blocks_n} (из них скопировано из клинера: {copied_n}), '
            f'вопросов в тестах: {q_n}.'
        ))
