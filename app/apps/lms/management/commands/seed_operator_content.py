def ptable(headers, rows):
    """Простая таблица цен (работает в светлой и тёмной теме)."""
    bd = 'border:1px solid rgba(128,128,128,.35);padding:7px 12px;'
    th = ''.join(f'<th style="{bd}text-align:left;">{h}</th>' for h in headers)
    body = ''
    for r in rows:
        body += '<tr>' + ''.join(f'<td style="{bd}">{c}</td>' for c in r) + '</tr>'
    return (f'<table style="width:100%;border-collapse:collapse;margin:12px 0;font-size:.95rem;">'
            f'<thead><tr>{th}</tr></thead><tbody>{body}</tbody></table>')


