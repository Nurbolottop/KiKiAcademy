def _flatten(course):
    """Собирает {название_урока: [блоки]} из структуры COURSE."""
    out = {}
    for _topic_title, lessons in course:
        for lesson_title, blocks in lessons:
            out[lesson_title] = blocks
    return out


class Command(BaseCommand):
    help = 'Дополняет курс «Обучение оператора» материалами (additive, без удаления).'

    def _append_blocks(self, lesson, blocks):
        """Дописывает блоки в урок, пропуская уже существующие (по тексту)."""
        added = 0
        existing = set(lesson.blocks.values_list('text', flat=True))
        max_order = max([b.order for b in lesson.blocks.all()], default=0)
        for _kind, text in blocks:
            if text in existing:
                continue
            max_order += 1
            LessonBlock.objects.create(
                lesson=lesson, kind=LessonBlock.Kind.TEXT, order=max_order, text=text,
            )
            existing.add(text)
            added += 1
        return added

    @transaction.atomic
    def command_body(self):
        try:
            course = Course.objects.get(title=COURSE_TITLE)
        except Course.DoesNotExist:
            self.stderr.write(self.style.ERROR(f'Курс «{COURSE_TITLE}» не найден.'))
            return

        content = _flatten(COURSE)
        topics = {t.order: t for t in course.topics.all()}

        n_new_lessons = n_blocks = 0
        skipped = []

        for lesson_title, blocks in content.items():
            route = ROUTING.get(lesson_title)
            if not route:
                skipped.append(f'нет маршрута: {lesson_title}')
                continue

            topic_order = route[1]
            topic = topics.get(topic_order)
            if topic is None:
                skipped.append(f'нет этапа order={topic_order} для «{lesson_title}»')
                continue

            if route[0] == 'enrich':
                target_title = route[2]
                lesson = topic.lessons.filter(title=target_title).first()
                if lesson is None:
                    skipped.append(f'нет урока «{target_title}» в этапе {topic_order} '
                                   f'(для «{lesson_title}»)')
                    continue
                n_blocks += self._append_blocks(lesson, blocks)
            else:  # add
                lesson = topic.lessons.filter(title=lesson_title).first()
                if lesson is None:
                    max_order = max([l.order for l in topic.lessons.all()], default=0)
                    lesson = Lesson.objects.create(
                        topic=topic, title=lesson_title, order=max_order + 1,
                        kind=Lesson.Kind.CONTENT, is_published=True,
                    )
                    n_new_lessons += 1
                n_blocks += self._append_blocks(lesson, blocks)

        self.stdout.write(self.style.SUCCESS(
            f'Готово (additive). Новых уроков: {n_new_lessons}. '
            f'Добавлено блоков: {n_blocks}. Ничего не удалено.'))
        if skipped:
            self.stdout.write(self.style.WARNING('Пропущено:'))
            for s in skipped:
                self.stdout.write('  - ' + s)

    def handle(self, *args, **options):
        self.command_body()
