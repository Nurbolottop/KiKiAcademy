# Новые уроки (в существующий этап), если темы нет вовсе: [(этап, урок, ключ G)]
NEW_LESSONS = [
    ('ЭТАП 1 — Введение', 'Дресс-код и рабочее место', 'Дресс-код и рабочее место'),
]


class Command(BaseCommand):
    help = 'ДОПИСЫВАЕТ тексты из GPT в короткие уроки оператора. Ничего не удаляет.'

    @transaction.atomic
    def handle(self, *args, **options):
        course = Course.objects.filter(title=COURSE_TITLE).first()
        if not course:
            self.stdout.write(self.style.WARNING(f'Курс «{COURSE_TITLE}» не найден.'))
            return

        added = 0
        for lesson_title, keys in APPEND.items():
            lesson = Lesson.objects.filter(topic__course=course, title=lesson_title).first()
            if not lesson:
                self.stdout.write(self.style.WARNING(f'  урок не найден (пропуск): {lesson_title}'))
                continue
            nxt = (lesson.blocks.order_by('-order').first().order if lesson.blocks.exists() else 0)
            for k in keys:
                nxt += 1
                LessonBlock.objects.create(lesson=lesson, kind=LessonBlock.Kind.TEXT,
                                           order=nxt, text=G[k])
                added += 1
            self.stdout.write(f'  + {lesson_title}: дописано {len(keys)} блок(ов)')

        for topic_title, lesson_title, key in NEW_LESSONS:
            topic = Topic.objects.filter(course=course, title=topic_title).first()
            if not topic:
                continue
            lesson, created = Lesson.objects.get_or_create(
                topic=topic, title=lesson_title,
                defaults={'kind': Lesson.Kind.CONTENT, 'is_published': True,
                          'order': (topic.lessons.count() + 1)})
            if not lesson.blocks.exists():
                LessonBlock.objects.create(lesson=lesson, kind=LessonBlock.Kind.TEXT,
                                           order=1, text=G[key])
                added += 1
                self.stdout.write(f'  + новый урок: {lesson_title}')

        self.stdout.write(self.style.SUCCESS(f'Готово. Добавлено блоков: {added}.'))
