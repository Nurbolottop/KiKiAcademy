class Command(BaseCommand):
    help = 'Создаёт структуру обучения (9 этапов) для роли Клинер без контента (ЭТАП 1 — с общими стандартами).'

    @transaction.atomic
    def handle(self, *args, **options):
        course, created = Course.objects.get_or_create(
            title=COURSE_TITLE,
            defaults={'icon': COURSE_ICON, 'order': 1,
                      'description': 'Базовая программа обучения клинера.'},
        )
        self.stdout.write(('Создан' if created else 'Найден') + f' курс: {course.title}')

        # Назначаем курс роли CLEANER.
        cleaner = Role.objects.filter(code=Role.Code.CLEANER).first()
        if cleaner:
            RoleCourse.objects.get_or_create(role=cleaner, course=course, defaults={'is_required': True})
            self.stdout.write(f'Курс назначен роли: {cleaner.title}')
        else:
            self.stdout.write(self.style.WARNING('Роль CLEANER не найдена — курс не назначен.'))

        topics_n = lessons_n = blocks_n = 0
        for t_order, (stage_title, lessons) in enumerate(CURRICULUM, start=1):
            topic, t_created = Topic.objects.get_or_create(
                course=course, title=stage_title, defaults={'order': t_order},
            )
            if not t_created and topic.order != t_order:
                topic.order = t_order
                topic.save(update_fields=['order'])
            topics_n += int(t_created)

            for l_order, (lesson_title, kind) in enumerate(lessons, start=1):
                lesson, l_created = Lesson.objects.get_or_create(
                    topic=topic, title=lesson_title,
                    defaults={'order': l_order, 'kind': kind, 'is_published': True},
                )
                lessons_n += int(l_created)

                # ЭТАП 1: наполняем общими стандартами (один раз).
                html = STAGE1_CONTENT.get(lesson_title) if stage_title.startswith('ЭТАП 1') else None
                if html and not lesson.blocks.exists():
                    LessonBlock.objects.create(
                        lesson=lesson, kind=LessonBlock.Kind.TEXT, order=1, text=html,
                    )
                    blocks_n += 1

        self.stdout.write(self.style.SUCCESS(
            f'Готово. Новых тем: {topics_n}, уроков: {lessons_n}, контент-блоков (ЭТАП 1): {blocks_n}.'
        ))
