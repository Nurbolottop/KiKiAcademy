class Command(BaseCommand):
    help = 'Наполняет курс «Обучение менеджера» — этапы 1 и 6 (контент + тесты).'
    _img_seq = 0

    def add_arguments(self, parser):
        parser.add_argument('--no-images', action='store_true',
                            help='Не скачивать фото, только текст/подписи.')

    @transaction.atomic
    def handle(self, *args, **options):
        no_images = options['no_images']
        course = Course.objects.filter(title=COURSE_TITLE).first()
        if not course:
            self.stdout.write(self.style.WARNING(
                f'Курс «{COURSE_TITLE}» не найден. Сначала: seed_manager_curriculum.'))
            return

        cleaner_topic = Topic.objects.filter(
            course__title=CLEANER_COURSE_TITLE, title=CLEANER_TOPIC_TITLE).first()

        blocks_n = q_n = copied_n = img_ok = img_fail = 0
        for topic_title, data in STAGES.items():
            topic = Topic.objects.filter(course=course, title=topic_title).first()
            if not topic:
                self.stdout.write(self.style.WARNING(f'  Этап не найден: {topic_title}'))
                continue

            for l_order, (lesson_title, blocks) in enumerate(data['lessons'], start=1):
                lesson = Lesson.objects.filter(topic=topic, title=lesson_title).first()
                if not lesson:
                    self.stdout.write(self.style.WARNING(f'    Урок не найден: {lesson_title}'))
                    continue
                lesson.order = l_order
                lesson.save(update_fields=['order'])
                lesson.blocks.all().delete()
                b_order = 0
                for b_order, item in enumerate(blocks, start=1):
                    kind = item[0]
                    if kind == 'image':
                        caption = item[1]
                        query = item[2] if len(item) > 2 else None
                        block = LessonBlock.objects.create(
                            lesson=lesson, kind=LessonBlock.Kind.IMAGE,
                            order=b_order, caption=caption)
                        if query and not no_images:
                            img, _src = fetch_commons_image(query)
                            if img:
                                self._img_seq += 1
                                block.caption = f'{caption} · фото: Wikimedia Commons'
                                block.image.save(f'manager-{self._img_seq}.jpg',
                                                 ContentFile(img), save=True)
                                img_ok += 1
                                self.stdout.write(f'      🖼  {caption}: фото загружено')
                            else:
                                img_fail += 1
                                self.stdout.write(self.style.WARNING(
                                    f'      ! {caption}: фото не найдено'))
                    elif kind == 'video':
                        url, caption = item[1]
                        LessonBlock.objects.create(lesson=lesson, kind=LessonBlock.Kind.VIDEO,
                                                   order=b_order, video_url=url, caption=caption)
                    else:
                        LessonBlock.objects.create(lesson=lesson, kind=LessonBlock.Kind.TEXT,
                                                   order=b_order, text=item[1])
                    blocks_n += 1

                # Подробный контент услуги из курса клинера
                src_title = CLEANER_SOURCES.get(lesson_title)
                if src_title and cleaner_topic:
                    src_lesson = Lesson.objects.filter(topic=cleaner_topic, title=src_title).first()
                    if src_lesson:
                        b_order += 1
                        LessonBlock.objects.create(
                            lesson=lesson, kind=LessonBlock.Kind.TEXT, order=b_order,
                            text=note('<strong>Подробно об услуге</strong> (из обучения клинера) — '
                                      'чтобы контролировать бригаду и консультировать клиента.'))
                        blocks_n += 1
                        for src in src_lesson.blocks.order_by('order', 'id'):
                            b_order += 1
                            new = LessonBlock(lesson=lesson, kind=src.kind, order=b_order,
                                              text=src.text, caption=src.caption,
                                              video_url=src.video_url)
                            if src.image:
                                new.image.name = src.image.name
                            new.save()
                            blocks_n += 1
                            copied_n += 1

            quiz = Lesson.objects.filter(topic=topic, title='Тест', kind=Lesson.Kind.QUIZ).first()
            if quiz and data.get('quiz'):
                quiz.order = len(data['lessons']) + 1
                quiz.pass_threshold = PASS_THRESHOLD
                quiz.save(update_fields=['order', 'pass_threshold'])
                quiz.questions.all().delete()
