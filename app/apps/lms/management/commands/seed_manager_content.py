def _callout(html, color):
    return (f'<div style="background:{color}1f;border-left:4px solid {color};'
            f'padding:12px 16px;border-radius:10px;margin:14px 0;">{html}</div>')


def warn(html):
    return _callout('⚠️ ' + html, '#ef4444')


def note(html):
    return _callout('ℹ️ ' + html, '#6c63ff')


def ok(html):
    return _callout('✅ ' + html, '#22c55e')


def li(*items):
    return '<ul>' + ''.join(f'<li>{i}</li>' for i in items) + '</ul>'


def ol(*items):
    return '<ol>' + ''.join(f'<li>{i}</li>' for i in items) + '</ol>'


def t(html):
    return ('text', html)


def ptable(headers, rows):
    bd = 'border:1px solid rgba(128,128,128,.35);padding:7px 12px;'
    th = ''.join(f'<th style="{bd}text-align:left;">{h}</th>' for h in headers)
    body = ''
    for r in rows:
        body += '<tr>' + ''.join(f'<td style="{bd}">{c}</td>' for c in r) + '</tr>'
    return (f'<table style="width:100%;border-collapse:collapse;margin:12px 0;font-size:.95rem;">'
            f'<thead><tr>{th}</tr></thead><tbody>{body}</tbody></table>')


def pre(text):
    return ('<pre style="background:rgba(128,128,128,.12);border-radius:10px;padding:14px 16px;'
            'overflow-x:auto;font-size:.9rem;line-height:1.5;white-space:pre-wrap;'
            'font-family:ui-monospace,Menlo,Consolas,monospace;margin:12px 0;">' + text + '</pre>')


